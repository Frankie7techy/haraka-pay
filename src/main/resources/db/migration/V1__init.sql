-- HarakaPay schema
-- Written to be portable across PostgreSQL (dev/prod) and H2 in PostgreSQL mode (test/CI):
-- no vendor-specific types, identity columns and plain constraints only.

CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    full_name VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE wallet_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(16) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    currency CHAR(3) NOT NULL,
    balance_minor BIGINT NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE transfer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_account_id BIGINT NOT NULL REFERENCES wallet_account(id),
    target_account_id BIGINT NOT NULL REFERENCES wallet_account(id),
    amount_minor BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    failure_reason VARCHAR(60),
    narrative VARCHAR(140),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE ledger_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id BIGINT REFERENCES transfer(id),
    account_id BIGINT NOT NULL REFERENCES wallet_account(id),
    direction VARCHAR(10) NOT NULL,
    amount_minor BIGINT NOT NULL,
    balance_after_minor BIGINT NOT NULL,
    narrative VARCHAR(140),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE idempotency_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id),
    idempotency_key VARCHAR(64) NOT NULL,
    endpoint VARCHAR(64) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    status_code INT NOT NULL,
    response_body TEXT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_idempotency_user_key UNIQUE (user_id, idempotency_key)
);

CREATE INDEX idx_ledger_entry_account ON ledger_entry (account_id, id);
CREATE INDEX idx_transfer_source ON transfer (source_account_id, created_at);
CREATE INDEX idx_transfer_target ON transfer (target_account_id, created_at);
